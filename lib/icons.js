// Devuelve el marcado de un icono listo para insertar.
// Los iconos son decorativos: el texto o el aria-label del control
// que los contiene es lo que anuncian los lectores de pantalla.
export function icon(name, className = "") {
    const body = PATHS[name];
    if (!body) {
        // Un icono inexistente debe verse en desarrollo, no fallar en silencio
        throw new Error(`Icono desconocido: "${name}"`);
    }
    const cls = className ? ` class="${className}"` : "";
    // width/height explícitos: sin ellos un SVG inline sin regla CSS
    // propia se estiraría al tamaño por defecto de reemplazo (300×150).
    return `<svg${cls} xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" ` +
        `stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" ` +
        `aria-hidden="true" focusable="false">${body}</svg>`;
}

export function hasIcon(name) {
    return Object.prototype.hasOwnProperty.call(PATHS, name);
}

// Logo de la marca: las mismas ondas del icono "waves", pero con un
// trazo más grueso para que funcione a tamaño pequeño.
export function logoMark(size = 22) {
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" ` +
        `stroke="currentColor" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round" ` +
        `style="width:${size}px;height:${size}px" aria-hidden="true" focusable="false">${PATHS.waves}</svg>`;
}
